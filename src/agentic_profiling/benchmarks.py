import argparse
import random
from pathlib import Path

import yaml
from datasets import load_dataset


def hotpotqa(n: int, seed: int) -> list[dict]:
    ds = load_dataset("hotpotqa/hotpot_qa", "distractor", split="validation")
    idx = sorted(random.Random(seed).sample(range(len(ds)), n))
    return [{"id": f"hotpot_{i:04d}", "question": ds[i]["question"], "expected": [ds[i]["answer"]],
             "metric": "hotpotqa", "tools": ["search", "lookup", "calculator"],
             "type": ds[i]["type"], "level": ds[i]["level"]} for i in idx]


def gsm8k(n: int, seed: int) -> list[dict]:
    ds = load_dataset("openai/gsm8k", "main", split="test")
    idx = sorted(random.Random(seed).sample(range(len(ds)), n))
    return [{"id": f"gsm8k_{i:04d}", "question": ds[i]["question"],
             "expected": [ds[i]["answer"].split("####")[-1].strip().replace(",", "")],
             "metric": "numeric", "tools": ["calculator", "python"]} for i in idx]


BUILDERS = {"hotpotqa": hotpotqa, "gsm8k": gsm8k}


def main() -> None:
    p = argparse.ArgumentParser(prog="agentic-tasks")
    p.add_argument("benchmark", choices=BUILDERS)
    p.add_argument("--n", type=int, default=100)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", type=Path)
    args = p.parse_args()

    tasks = BUILDERS[args.benchmark](args.n, args.seed)
    out = args.out or Path("tasks") / f"{args.benchmark}_{args.n}.yaml"
    header = f"# {args.benchmark}: {args.n} tasks, seed {args.seed} (generated by agentic-tasks)\n"
    out.write_text(header + yaml.safe_dump(tasks, sort_keys=False, allow_unicode=True, width=1000),
                   encoding="utf-8", newline="\n")
    print(f"Wrote {len(tasks)} tasks to {out}")
